const catalogues={en,de};
let current='en';
export function setLocale(code) { current=catalogues[code]?code:'en'; document.documentElement.lang=current; }
export const locale=()=>current;
// Text for module-level constants: translated when shown (template, esc(), String()), not when the module loads.
export const lazyText=key=>({ toString:()=>t(key), valueOf:()=>t(key), [Symbol.toPrimitive]:()=>t(key), toJSON:()=>t(key) });
export function t(key,vars) { const s=catalogues[current][key]??en[key]??key; return vars?s.replace(/\{(\w+)\}/g,(_,k)=>vars[k]??''):s; }
// Enum values from the API (statuses, priorities, roles, machine types); unknown values are shown humanised.
export const label=(group,value)=>value==null?'':(catalogues[current][`${group}.${value}`]??en[`${group}.${value}`]??String(value).replaceAll('_',' '));

const zoneOk=zone=>{ try { new Intl.DateTimeFormat('en',{timeZone:zone}); return true; } catch { return false; } };
// Times are shown in the zone where the work happens (the plant's), with the zone name, so a dispatcher in one
// country and an engineer in another read the same wall-clock time.
export function formatDateTime(iso,zone) {
  if (!iso) return '—';
  const timeZone=zone&&zoneOk(zone)?zone:undefined;
  return new Intl.DateTimeFormat(current,{year:'numeric',month:'short',day:'numeric',hour:'2-digit',minute:'2-digit',timeZone,timeZoneName:'short'}).format(new Date(iso));
}
export function formatDate(iso,zone) { if (!iso) return '—'; return new Intl.DateTimeFormat(current,{year:'numeric',month:'short',day:'numeric',timeZone:zone&&zoneOk(zone)?zone:'UTC'}).format(new Date(iso)); }
export const formatNumber=(n,digits=0)=>n==null?'—':new Intl.NumberFormat(current,{maximumFractionDigits:digits}).format(n);
const fractionDigits=code=>new Intl.NumberFormat('en',{style:'currency',currency:code}).resolvedOptions().maximumFractionDigits;
export const formatMoney=(minor,code)=>minor==null?'—':new Intl.NumberFormat(current,{style:'currency',currency:code}).format(minor/10**fractionDigits(code));
export const toMinorUnits=(major,code)=>Math.round(Number(major)*10**fractionDigits(code));
export const formatTemperature=(c,units)=>c==null?'—':units==='imperial'?`${formatNumber(c*9/5+32,1)} °F`:`${formatNumber(c,1)} °C`;
export function formatDuration(minutes) { if (minutes==null) return '—'; return minutes<120?`${formatNumber(minutes)} min`:minutes<2880?`${formatNumber(minutes/60,1)} ${t('label.hours')}`:`${formatNumber(minutes/1440,1)} ${t('label.days')}`; }
