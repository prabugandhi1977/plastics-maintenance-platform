-- Spare parts stock: a catalogue per company, stock per plant and storage bin, an append-only ledger of movements,
-- purchase orders still to arrive, and the parts each preventive maintenance plan needs.
-- Quantities are NUMERIC(14,3) because parts are counted in pieces and sets but also bought by the metre, kilogram or
-- litre. Costs are in the company currency's minor units (cents), like quotations.

CREATE TABLE spare_parts (
  id TEXT PRIMARY KEY,
  company_id TEXT NOT NULL REFERENCES companies(id) DEFERRABLE INITIALLY IMMEDIATE,
  part_number TEXT NOT NULL,
  name TEXT NOT NULL,
  maker TEXT NOT NULL DEFAULT '',
  unit TEXT NOT NULL DEFAULT 'pcs' CHECK (unit IN ('pcs','set','m','kg','l')),
  category TEXT NOT NULL DEFAULT '',
  -- Machine types the part fits (JSON array of equipment machine types); specific machines are in spare_part_fits.
  fits_types TEXT NOT NULL DEFAULT '[]',
  unit_cost_minor BIGINT NOT NULL DEFAULT 0 CHECK (unit_cost_minor >= 0),
  -- Reorder when on hand + on order falls below this (the minimum stock); order reorder_qty at a time.
  reorder_point NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (reorder_point >= 0),
  reorder_qty NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (reorder_qty >= 0),
  lead_time_days BIGINT NOT NULL DEFAULT 0 CHECK (lead_time_days >= 0),
  supplier TEXT NOT NULL DEFAULT '',
  -- The maker's or supplier's barcode on the packaging, if any; qr_code is the platform's own label (SP:...).
  barcode TEXT,
  qr_code TEXT NOT NULL UNIQUE,
  notes TEXT NOT NULL DEFAULT '',
  active BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (company_id, part_number)
);
CREATE INDEX idx_spare_parts_barcode ON spare_parts(company_id, barcode) WHERE barcode IS NOT NULL;

CREATE TABLE spare_part_fits (
  part_id TEXT NOT NULL REFERENCES spare_parts(id) DEFERRABLE INITIALLY IMMEDIATE,
  equipment_id TEXT NOT NULL REFERENCES equipment(id) DEFERRABLE INITIALLY IMMEDIATE,
  PRIMARY KEY (part_id, equipment_id)
);
CREATE INDEX idx_spare_part_fits_equipment ON spare_part_fits(equipment_id);

-- Quantity on hand per plant and bin. Kept in step with the ledger in the same transaction as every movement
-- (the ledger is the record; GET /api/spare-parts/reconcile compares the two).
CREATE TABLE spare_stock (
  id TEXT PRIMARY KEY,
  company_id TEXT NOT NULL,
  part_id TEXT NOT NULL REFERENCES spare_parts(id) DEFERRABLE INITIALLY IMMEDIATE,
  plant_id TEXT NOT NULL REFERENCES plants(id) DEFERRABLE INITIALLY IMMEDIATE,
  bin TEXT NOT NULL DEFAULT '',
  on_hand NUMERIC(14,3) NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL,
  UNIQUE (part_id, plant_id, bin)
);
CREATE INDEX idx_spare_stock_company ON spare_stock(company_id, plant_id);

CREATE TABLE spare_orders (
  id TEXT PRIMARY KEY,
  company_id TEXT NOT NULL,
  part_id TEXT NOT NULL REFERENCES spare_parts(id) DEFERRABLE INITIALLY IMMEDIATE,
  plant_id TEXT NOT NULL REFERENCES plants(id) DEFERRABLE INITIALLY IMMEDIATE,
  quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
  received_qty NUMERIC(14,3) NOT NULL DEFAULT 0,
  supplier TEXT NOT NULL DEFAULT '',
  reference TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','received','cancelled')),
  expected_at TEXT,
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX idx_spare_orders_part ON spare_orders(part_id, status);

-- The ledger. Signed quantities: receive, return and transfer_in add; issue and transfer_out take away; adjust either.
-- Rows are never changed or deleted (enforced below); a mistake is corrected with a further adjustment.
CREATE TABLE spare_movements (
  id TEXT PRIMARY KEY,
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  company_id TEXT NOT NULL,
  part_id TEXT NOT NULL REFERENCES spare_parts(id) DEFERRABLE INITIALLY IMMEDIATE,
  plant_id TEXT NOT NULL REFERENCES plants(id) DEFERRABLE INITIALLY IMMEDIATE,
  bin TEXT NOT NULL DEFAULT '',
  type TEXT NOT NULL CHECK (type IN ('receive','issue','return','adjust','transfer_out','transfer_in')),
  quantity NUMERIC(14,3) NOT NULL CHECK (quantity <> 0),
  balance_after NUMERIC(14,3) NOT NULL,
  unit_cost_minor BIGINT NOT NULL DEFAULT 0,
  ticket_id TEXT REFERENCES tickets(id) DEFERRABLE INITIALLY IMMEDIATE,
  equipment_id TEXT REFERENCES equipment(id) DEFERRABLE INITIALLY IMMEDIATE,
  parts_request_id TEXT,
  pm_job_id TEXT,
  order_id TEXT,
  transfer_id TEXT,
  reason TEXT NOT NULL DEFAULT '',
  reference TEXT NOT NULL DEFAULT '',
  user_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  CHECK ((type IN ('receive','return','transfer_in') AND quantity > 0) OR (type IN ('issue','transfer_out') AND quantity < 0) OR type = 'adjust'),
  CHECK (type <> 'adjust' OR reason <> '')
);
CREATE INDEX idx_spare_movements_part ON spare_movements(part_id, seq);
CREATE INDEX idx_spare_movements_ticket ON spare_movements(ticket_id) WHERE ticket_id IS NOT NULL;
CREATE INDEX idx_spare_movements_company ON spare_movements(company_id, created_at);

CREATE FUNCTION spare_movements_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Stock movements cannot be changed or deleted; record an adjustment instead';
END $$;
CREATE TRIGGER spare_movements_no_change BEFORE UPDATE OR DELETE ON spare_movements
  FOR EACH ROW EXECUTE FUNCTION spare_movements_immutable();

CREATE TABLE pm_plan_parts (
  plan_id TEXT NOT NULL REFERENCES pm_plans(id) DEFERRABLE INITIALLY IMMEDIATE,
  part_id TEXT NOT NULL REFERENCES spare_parts(id) DEFERRABLE INITIALLY IMMEDIATE,
  quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (plan_id, part_id)
);

-- A ticket's parts request can be fulfilled from a catalogue part in stock.
ALTER TABLE parts_requests ADD COLUMN spare_part_id TEXT;
